import app from "./app";
import { logger } from "./lib/logger";

const rawPort = process.env["PORT"];

if (!rawPort) {
  throw new Error(
    "PORT environment variable is required but was not provided.",
  );
}

const port = Number(rawPort);

if (Number.isNaN(port) || port <= 0) {
  throw new Error(`Invalid PORT value: "${rawPort}"`);
}

if (process.env.TERAS_BOOTSTRAP_SUPER_ADMIN_EMAIL?.trim()) {
  // Do not log the configured address. This bridge self-disables after its
  // immutable first-claim record exists and is intended only for publishing.
  logger.warn("One-time super-admin email bootstrap is configured");
}

app.listen(port, (err) => {
  if (err) {
    logger.error({ err }, "Error listening on port");
    process.exit(1);
  }

  logger.info({ port }, "Server listening");
});
